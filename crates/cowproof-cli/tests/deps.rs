#[test]
fn a_patch_to_registry_config_is_refused_and_the_fetch_still_uses_the_base_config() {
    if !sandbox_available() {
        return;
    }
    let cache = var_tmp("cp-deps-cache-");
    let project = vendored_project(None);
    let plain = lane(
        &project,
        &run_checks(&["ok"]),
        json!([{"id": "ok", "command": "true"}]),
        cache.path(),
    );
    run_expecting(&plain, 0);
    let plain_key = capsule(&plain).dependency_cache_key.unwrap();

    // The builder points the registry at a directory that does not exist. If the fetch
    // read this config it would fail; it reads the base's.
    let body = format!(
        "printf '[source.crates-io]\\nreplace-with = \"x\"\\n[source.x]\\ndirectory = \"nowhere\"\\n' > .cargo/config.toml\n{}",
        run_checks(&["ok"])
    );
    let patched = lane(
        &project,
        &body,
        json!([{"id": "ok", "command": "true"}]),
        cache.path(),
    );
    let out = run_expecting(&patched, 2);
    let verdict = patched.verdict();
    assert_eq!(verdict["verdict"], "refuted", "{verdict}");
    assert!(
        verdict["failedGates"]
            .as_array()
            .unwrap()
            .contains(&json!("protected_paths")),
        "{verdict}"
    );
    assert!(
        String::from_utf8_lossy(&out.stdout).contains(".cargo/config.toml"),
        "{}",
        text(&out)
    );
    let c = capsule(&patched);
    assert_eq!(c.dependency_fetch_outcome.as_deref(), Some("hit"));
    assert_eq!(c.dependency_cache_key.unwrap(), plain_key);
}

#[test]
fn the_verifier_builds_from_the_cache_mounted_read_only_and_a_held_out_build_proves_it() {
    if !sandbox_available() {
        return;
    }
    let cache = var_tmp("cp-deps-cache-");
    let registry = index_registry();
    // The builder cannot build here (its cargo home has no registry and no network), so
    // its own check is a no-op; the held-out build runs only in the verifier, which has
    // the fetched cache and nothing else to build from.
    let lane = lane(
        &registry.project,
        &run_checks(&["ok"]),
        json!([{"id": "ok", "command": "true"}]),
        cache.path(),
    );
    let held = var_tmp("cp-deps-held-");
    let heldout = held.path().join("h.toml");
    fs::write(
        &heldout,
        "[[check]]\nid = \"held-build\"\ncommand = \"cargo build --offline --locked\"\n",
    )
    .unwrap();
    let out = lane.run(&[Path::new("--heldout"), &heldout]);
    assert_eq!(out.status.code(), Some(0), "cowproof run:\n{}", text(&out));
    assert_eq!(lane.verdict()["verdict"], "proved");

    let c = capsule(&lane);
    assert_eq!(c.dependency_fetch_outcome.as_deref(), Some("fetched"));
    let key = c.dependency_cache_key.unwrap();
    let src = cache_entry(cache.path(), &key).join("cargo/registry/src");
    let unpacked: Vec<PathBuf> = fs::read_dir(&src)
        .unwrap()
        .map(|e| e.unwrap().path().join("tinydep-0.1.0"))
        .collect();
    assert!(
        unpacked.iter().any(|p| p.join("src/lib.rs").is_file()),
        "the fetch unpacked the crate into the cache: {unpacked:?}"
    );
}

#[test]
fn verify_on_another_cache_root_fetches_what_the_capsule_names_and_reproduces() {
    if !sandbox_available() {
        return;
    }
    let cache = var_tmp("cp-deps-cache-");
    let lane = lane(
        &vendored_project(None),
        &run_checks(&["build"]),
        build_check(),
        cache.path(),
    );
    run_expecting(&lane, 0);
    let key = capsule(&lane).dependency_cache_key.unwrap();

    // Another machine: a fresh clone and an empty cache root.
    let fresh = var_tmp("cp-deps-fresh-");
    let clone = fresh.path().join("repo");
    let cloned = output(
        Command::new("git")
            .args(["clone", "-q"])
            .arg(&lane.repo)
            .arg(&clone),
    );
    assert!(cloned.status.success(), "{}", text(&cloned));
    let other_cache = var_tmp("cp-deps-other-");
    let workdir = var_tmp("cp-deps-wd-");
    let verify = |net: &str| {
        output(
            lane.cowproof_cmd()
                .env("COWPROOF_CACHE_ROOT", other_cache.path())
                .env("COWPROOF_FETCH_NETWORK", net)
                .current_dir(fresh.path())
                .arg("verify")
                .arg(lane.capsule_dir())
                .arg("--repo")
                .arg(&clone)
                .arg("--workdir")
                .arg(workdir.path()),
        )
    };
    let out = verify("none");
    assert_eq!(out.status.code(), Some(0), "{}", text(&out));
    // A cargo build prints paths and timings that differ in the rebuilt tree, so the result
    // line may be followed by the note that the output is not byte-identical (never a failure).
    let said = String::from_utf8_lossy(&out.stdout).to_string();
    assert_eq!(said.lines().next(), Some("reproduced"), "{said}");
    assert!(
        said.lines()
            .skip(1)
            .all(|l| l.starts_with("note: check \"build\"")),
        "{said}"
    );
    assert!(
        cache_entry(other_cache.path(), &key)
            .join("cargo/registry")
            .is_dir(),
        "verify fetched the capsule's key into its own cache root"
    );
}

